def get_variable_metadata(tag: str) -> ProcessVariable:
    """Retrieve metadata for a specified variable tag."""
    if tag not in VARIABLE_CATALOG:
        raise KeyError(f"Variable tag '{tag}' not found in TEP variable catalog.")
    return VARIABLE_CATALOG[tag]


def get_catalog_dataframe() -> pd.DataFrame:
    """Return the entire catalog as a formatted pandas DataFrame for UI and documentation."""
    rows = []
    for var in VARIABLE_CATALOG.values():
        rows.append({
            "Tag": var.tag,
            "Index": var.index,
            "Name": var.name,
            "Type": "Manipulated (XMV)" if var.is_manipulated else "Measured (XMEAS)",
            "Units": var.units,
            "Nominal": var.nominal_setpoint,
            "Min": var.min_bound,
            "Max": var.max_bound,
            "Low Alarm": var.low_alarm,
            "High Alarm": var.high_alarm,
            "Low Shutdown": var.low_shutdown,
            "High Shutdown": var.high_shutdown,
            "Description": var.description,
        })
    return pd.DataFrame(rows)
